#!/usr/bin/env python3
"""Canonical locale-only generation, independent of bitmap/art dependencies.

All 36 dictionaries are packaged separately; the VM loads only one. Resource
presence is not qualification. Runtime/manifest use source-bound software proof.
"""
import json
from pathlib import Path
from xml.sax.saxutils import escape
import xml.etree.ElementTree as ET
try:
 from tools.localization import load_locales
 from tools.native_language_policy import software_locales
except ImportError:
 from localization import load_locales
 from native_language_policy import software_locales
ROOT=Path(__file__).resolve().parents[1]
ALIASES={'chs':'zhs','cht':'zht'}
FACES={'ar':'NotoNaskhArabicRegular','he':'NotoSansHebrewRegular','zh-Hans':'NotoSansSCMedium','zh-Hant':'NotoSansSCMedium','ja':'KosugiRegular','ko':'NanumGothicBold','th':'PridiRegular'}

def resource_code(row): return ALIASES.get(row['garmin'],row['garmin'])
def scene_strings(rows,qualified):
 # Scalar IDs/ResourceIds only. No eager translation dictionaries or fonts.
 source='// Generated by tools/build_native_localization.py from canonical36 catalog.\nimport Toybox.Lang;\nimport Toybox.System;\n(:extendedCode, :typecheck(false)) module SceneStrings {\n'
 source+=' var packedIds as String = '+json.dumps('|'.join(r['id'] for r in rows)+'|')+';\n var packedCodes as String = '+json.dumps('|'.join(r['garmin'] for r in rows)+'|')+';\n'
 source+=' function locale(index as Number) as String {var start=0;var n=0;for(var i=0;i<packedIds.length();i+=1){if(packedIds.substring(i,i+1).equals("|")){if(n==index){return packedIds.substring(start,i);}n+=1;start=i+1;}}return "en";}\n'
 source+=' function resource(index as Number) as ResourceId {switch(index){'+''.join('case '+str(i)+':return Rez.JsonData.'+name+';' for i,name in enumerate("Locale"+str(i) for i in range(len(rows))))+'}return Rez.JsonData.Locale0;}\n'
 source+=' function available(index as Number) as Boolean {return '+('||'.join('index=='+str(i) for i,r in enumerate(rows) if r['id']=='en' or r['id'] in qualified))+';}\n'
 source+=' function index(value as Object or Null) as Number {if(value instanceof Number&&value>=0&&value<36){return value;}if(value instanceof String){for(var i=0;i<36;i+=1){if(locale(i).equals(value)){return i;}}}return 0;}\n'
 source+=' function systemIndex(code as Object or Null) as Number {if(code instanceof Number){switch(code){'+''.join('case System.LANGUAGE_'+r["garmin"].upper()+':return '+str(i)+';' for i,r in enumerate(rows))+'}}if(!(code instanceof String)){return 0;}if(code.equals("zhs")){code="chs";}if(code.equals("zht")){code="cht";}if(code.length()!=3){return 0;}var n=packedCodes.find(code+"|");return n==null||n%4!=0?0:n/4;}\n}\n'
 return source

def generate(root=ROOT):
 loaded=load_locales(root);catalog=loaded["catalog"];labels=loaded["strings"]
 rows=catalog['locales'];qualified=software_locales(root,catalog);res=root/'watchface/resources';gen=root/'watchface/source/generated';gen.mkdir(parents=True,exist_ok=True)
 def write(p,s):p.parent.mkdir(parents=True,exist_ok=True);p.write_text(s,encoding='utf-8')
 def strings_xml(texts):return '<strings>\n'+''.join(f'<string id="{k}">{escape(v)}</string>\n' for k,v in texts.items())+'</strings>\n'
 json_ids=[]
 for index,row in enumerate(rows):
  loc=row['id'];d=labels[loc];code=resource_code(row)
  texts={'AppName':'SpaceFox','Energy':'Body Battery','Language':d['language'],'FeedBaseUrl':d['feedUrl'],'Auto':d['auto'],'English':'English','Russian':'Русский'}
  appearance={
   'en':['Clock color','Countdown color','Field {n} color','Mint','White','Ice blue','Lavender','Gold','Pink'],
   'ru':['Цвет часов','Цвет отсчёта','Цвет поля {n}','Мятный','Белый','Голубой','Сиреневый','Золотой','Розовый'],
   'de':['Uhrfarbe','Countdown-Farbe','Farbe Feld {n}','Mint','Weiß','Hellblau','Lavendel','Gold','Rosa'],
   'fr':['Couleur heure','Couleur décompte','Couleur champ {n}','Menthe','Blanc','Bleu clair','Lavande','Or','Rose'],
   'es':['Color de hora','Color de cuenta','Color campo {n}','Menta','Blanco','Azul claro','Lavanda','Dorado','Rosa']}
  colors=appearance.get(loc,appearance['en'])
  texts.update({'ClockColor':colors[0],'CountdownColor':colors[1]})
  texts.update({'Field'+str(i)+'Color':colors[2].replace('{n}',str(i)) for i in range(1,5)})
  texts.update({'Color'+str(i):value for i,value in enumerate(colors[3:])})
  texts.update({k.capitalize():d[k] for k in ['steps','heart','stress','battery','calories']})
  texts.update({'Field'+str(i):d['field'].replace('{n}',str(i)) for i in range(1,5)})
  texts.update({'Locale'+str(i):r['name'] for i,r in enumerate(rows)})
  directory=res if loc=='en' else root/'watchface'/('resources-'+code)
  write(directory/'strings/strings.xml',strings_xml(texts))
  # JSON resources do not allocate a global dictionary for every language.
  ident='Locale'+str(index);json_ids.append(ident)
  payload={k:d[k] for k in ['hour','minute','day','second','noSchedule','dateOnly','window','timeUnknown','awaitUpdate','companyUnknown','missionUnknown']}
  payload.update(locale=loc,face=FACES.get(loc,'RobotoRegular'),rtl=row['direction']=='rtl',group=(' ' if loc in 'ru uk pl cs sk hu ro bg hr sl fi sv nb et lv lt fr'.split() else '.' if loc in 'de es it pt nl el tr da id'.split() else ','),dateOrder=('ymd' if loc in ['zh-Hans','zh-Hant','ja','ko','hu','lt','sv'] else 'mdy' if loc=='en' else 'dmy'))
  write(res/'json'/f'{ident}.json',json.dumps(payload,ensure_ascii=False,separators=(',',':'))+'\n')
 write(res/'json/locales.xml','<resources>\n'+''.join(f'<jsonData id="{i}" filename="{i}.json"/>\n' for i in json_ids)+'</resources>\n')
 settings=['<settings>'];props=['<properties>'];roles=['Steps','Energy','Heart','Stress','Calories','Battery']
 for i in range(1,5):
  props.append(f'<property id="Field{i}" type="number">{i-1}</property>')
  settings.append(f'<setting propertyKey="@Properties.Field{i}" title="@Strings.Field{i}"><settingConfig type="list">'+''.join(f'<listEntry value="{n}">@Strings.{role}</listEntry>' for n,role in enumerate(roles))+'</settingConfig></setting>')
 options=[(i,'Locale'+str(i)) for i,row in enumerate(rows) if row['id'] in catalog['supportPolicy']['primaryLocales']]+[(36,'Auto')]
 props.append('<property id="Language" type="number">0</property>');settings.append('<setting propertyKey="@Properties.Language" title="@Strings.Language"><settingConfig type="list">'+''.join(f'<listEntry value="{n}">@Strings.{role}</listEntry>' for n,role in options)+'</settingConfig></setting>')
 for key,default in [('ClockColor',0),('CountdownColor',0)]+[('Field'+str(i)+'Color',1) for i in range(1,5)]:
  props.append(f'<property id="{key}" type="number">{default}</property>')
  settings.append(f'<setting propertyKey="@Properties.{key}" title="@Strings.{key}"><settingConfig type="list">'+''.join(f'<listEntry value="{n}">@Strings.Color{n}</listEntry>' for n in range(6))+'</settingConfig></setting>')
 props.append('<property id="FeedBaseUrl" type="string"></property>');settings.append('<setting propertyKey="@Properties.FeedBaseUrl" title="@Strings.FeedBaseUrl"><settingConfig type="alphaNumeric"/></setting>')
 write(res/'settings/properties.xml','\n'.join(props+['</properties>'])+'\n');write(res/'settings/settings.xml','\n'.join(settings+['</settings>'])+'\n')
 write(gen/'SceneStrings.mc',scene_strings(rows,qualified))
 # Only explicitly software-observed primary modes join English bootstrap.
 # Human/device nativeQualified metadata remains independent.
 ns='http://www.garmin.com/xml/connectiq';ET.register_namespace('iq',ns)
 p=root/'watchface/manifest.xml';tree=ET.parse(p);langs=tree.find('.//{'+ns+'}languages');langs.clear()
 for r in rows:
  if r['id']=='en' or r['id'] in qualified:ET.SubElement(langs,'{'+ns+'}language').text=resource_code(r)
 tree.write(p,encoding='unicode',xml_declaration=True)
 write(root/'watchface/monkey.jungle','project.manifest = manifest.xml\nbase.sourcePath = source\nbase.resourcePath = resources\n'+''.join('base.lang.'+resource_code(r)+' = resources-'+resource_code(r)+'\n' for r in rows if r['id']!='en'))
if __name__=='__main__':generate()
