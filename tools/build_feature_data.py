"""SPDX-License-Identifier: MIT. Bundle original experiment data, not workflow code."""
import json
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]


def content():
    folder = ROOT / 'prototype/features'
    data = {key: json.loads((folder / name).read_text()) for key, name in [
        ('axes', 'axes.json'), ('fonts', 'font-manifest.json'),
        ('rockets', 'rocket-catalog.json'), ('legacy', 'legacy.json')]}
    return '/* SPDX-License-Identifier: MIT. Generated by tools/build_feature_data.py. */\nwindow.SpaceFoxFeatureData=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'prototype/features/data.js'
    if args.check:
        assert target.read_text() == content(), 'feature bundle drift'
    else:
        target.write_text(content())
