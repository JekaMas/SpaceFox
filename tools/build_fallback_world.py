#!/usr/bin/env python3
"""Generate a bounded, direct-draw Natural Earth fallback (no raster allocation)."""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'watchface/source/generated/FallbackWorld.mc'


def simplify(points, tolerance):
    if len(points) < 3:
        return points
    x1, y1 = points[0]
    x2, y2 = points[-1]
    scale = math.hypot(x2 - x1, y2 - y1) or 1
    distance = [abs((y2-y1)*x - (x2-x1)*y + x2*y1 - y2*x1) / scale for x, y in points]
    furthest = max(distance)
    index = distance.index(furthest)
    if furthest <= tolerance:
        return [points[0], points[-1]]
    return simplify(points[:index+1], tolerance)[:-1] + simplify(points[index:], tolerance)


def render():
    source = json.loads((ROOT / 'catalog/world.json').read_text())['lines']
    lines = [[(round((lon+180)*194/360), round((90-lat)*97/180)) for lon, lat in row] for row in source if len(row) > 2]
    lines = [simplify(row, 1) for row in lines]
    lines.sort(key=lambda row: sum(math.dist(a, b) for a, b in zip(row, row[1:]) if abs(a[0]-b[0]) < 97), reverse=True)
    segments = []
    for line in lines[:40]:
        for a, b in zip(line, line[1:]):
            if a != b and abs(a[0]-b[0]) < 97:
                segments.extend((*a, *b))
    if any(value < 0 or value > 255 for value in segments):
        raise ValueError('fallback coordinate does not fit an unsigned byte')
    result = ['// Generated by tools/build_fallback_world.py from catalog/world.json.',
              'import Toybox.Graphics;', 'import Toybox.Lang;',
              'module FallbackWorld {',
              '    var segments as ByteArray = [' + ','.join(map(str, segments)) + ']b;',
              '    function draw(dc as Graphics.Dc, x as Number, y as Number) as Void {',
              '        dc.setColor(0x536574, Graphics.COLOR_TRANSPARENT);',
              '        for(var i=0;i<segments.size();i+=4){',
              '            dc.drawLine(x+segments[i],y+segments[i+1],x+segments[i+2],y+segments[i+3]);',
              '        }']
    return '\n'.join(result + ['    }', '}', ''])


if __name__ == '__main__':
    import sys
    if '--check' in sys.argv:
        if OUT.read_text() != render():
            raise SystemExit('fallback world source is stale')
    else:
        OUT.write_text(render())
