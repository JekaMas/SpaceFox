#!/usr/bin/env python3
"""Validate locale resources and build the read-only preview and retained source geometry."""
import argparse
import json
from pathlib import Path
import re
import sys

from localization import load_locales, read_json, validate_inventory


def outputs(root):
    bundle = load_locales(root)
    validate_inventory(root, read_json(root / 'distribution/components.json'))
    prototype = root / 'prototype'
    template = (prototype / 'mission.template.html').read_text(encoding='utf-8')
    examples = read_json(prototype / 'launch-examples.json')
    page = """<!doctype html>
<!-- Generated by tools/build_preview.py. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>SpaceFox simulator preview</title>
<style>body{font:16px system-ui,sans-serif;color:#e8f1fa;background:#08111d;max-width:900px;margin:2rem auto;padding:0 1rem}figure{display:inline-block;margin:1rem}img{width:min(100%,390px);height:auto}a{color:#9be5ed}</style>
</head><body><main><h1>SpaceFox simulator preview</h1>
<p>English and Russian candidate captures from the native FR165 simulator. These are existing observations, not physical-device or Store acceptance.</p>
<figure><img src="../openspec/changes/spacefox-watchface/evidence/current-native-ui/frames/en-face.png" alt="English native simulator candidate"><figcaption>English candidate</figcaption></figure>
<figure><img src="../openspec/changes/spacefox-watchface/evidence/current-native-ui/frames/ru-face.png" alt="Russian native simulator candidate"><figcaption>Russian candidate</figcaption></figure>
<p><a href="../README.md">Read about SpaceFox</a> · <a href="../THIRD_PARTY_NOTICES.md">Third-party notices</a></p>
</main></body></html>
"""
    world = re.search(r'<script type="application/json" id="mission-world-topology">(.*?)</script>', template, re.S)
    if not world:
        raise ValueError('template: canonical world topology missing')
    lab = {'world': json.loads(world.group(1)), 'launches': examples,
           'strings': {key: bundle['strings'][key] for key in ['ru', 'en']}}
    lab_json = json.dumps(lab, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')
    art_start = template.index('  #launch-watch-mission .core {')
    art_end = template.index('  #launch-watch-mission .mission-details {', art_start)
    rocket_css = '/* Generated from the canonical Mission schematic artwork; MIT. */\n' + template[art_start:art_end].replace('#launch-watch-mission', '.face')
    return {prototype / 'index.html': page,
            prototype / 'layout-data.js': '/* Generated by tools/build_preview.py; original data / Natural Earth. */\nwindow.SpaceFoxLayoutData=' + lab_json + ';\n',
            prototype / 'layout-rocket.css': rocket_css}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Reject stale generated output without writing')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for path, content in outputs(root).items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(root)))
        else:
            path.write_text(content, encoding='utf-8')
    if stale:
        print('Stale preview: ' + ', '.join(stale), file=sys.stderr)
        return 1
    print('Preview resources validated; ' + ('generated output is current' if args.check else 'preview generated'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
