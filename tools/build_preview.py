#!/usr/bin/env python3
"""Build the original standalone preview without a service-owned shell."""
import argparse
import json
from pathlib import Path
import re
import sys

from localization import load_locales, read_json, validate_inventory


def outputs(root):
    bundle = load_locales(root)
    validate_inventory(root, read_json(root / 'distribution/components.json'))
    prototype = root / 'prototype'
    template = (prototype / 'mission.template.html').read_text(encoding='utf-8')
    payload = json.dumps(bundle, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')
    app = '<script type="application/json" id="mission-locales">' + payload + '</script>\n'
    examples = read_json(prototype / 'launch-examples.json')
    example_json = json.dumps(examples, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')
    app += '<script type="application/json" id="mission-examples">' + example_json + '</script>\n'
    for name in ['i18n.js', 'mission.js']:
        app += '<script>\n' + (prototype / name).read_text(encoding='utf-8') + '\n</script>\n'
    if template.count('<!--SPACEFOX_APP-->') != 1:
        raise ValueError('template: expected one app insertion point')
    fragment = template.replace('<!--SPACEFOX_APP-->', app).rstrip() + '\n'
    page = '''<!doctype html>
<!-- Generated by tools/build_preview.py. Original SpaceFox shell; MIT. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>SpaceFox · Forerunner 165</title><link rel="stylesheet" href="standalone.css">
<script src="vendor/lucide-0.468.0.min.js"></script></head><body><main>
<header><h1>SpaceFox</h1><a href="../README.md">README</a></header>
'''+fragment+'''
<footer>MIT · <a href="../THIRD_PARTY_NOTICES.md">Third-party notices</a> · <a href="../docs/LOCALIZATION.md">Localization</a></footer>
</main></body></html>
'''
    world = re.search(r'<script type="application/json" id="mission-world-topology">(.*?)</script>', template, re.S)
    if not world:
        raise ValueError('template: canonical world topology missing')
    lab = {'world': json.loads(world.group(1)), 'launches': examples,
           'strings': {key: bundle['strings'][key] for key in ['ru', 'en']}}
    lab_json = json.dumps(lab, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')
    art_start = template.index('  #launch-watch-mission .core {')
    art_end = template.index('  #launch-watch-mission .mission-details {', art_start)
    rocket_css = '/* Generated from the canonical Mission schematic artwork; MIT. */\n' + template[art_start:art_end].replace('#launch-watch-mission', '.face')
    return {prototype / 'mission.html': fragment, prototype / 'index.html': page,
            prototype / 'layout-data.js': '/* Generated by tools/build_preview.py; original data / Natural Earth. */\nwindow.SpaceFoxLayoutData=' + lab_json + ';\n',
            prototype / 'layout-rocket.css': rocket_css}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Reject stale generated output without writing')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for path, content in outputs(root).items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(root)))
        else:
            path.write_text(content, encoding='utf-8')
    if stale:
        print('Stale preview: ' + ', '.join(stale), file=sys.stderr)
        return 1
    print('Preview resources validated; ' + ('generated output is current' if args.check else 'preview generated'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
