"""Generate a runtime version and reproducible identity for its native inputs."""
import hashlib
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parents[1]
GENERATED = 'watchface/source/generated/NativeVersion.mc'

def render(root=ROOT):
    app = ElementTree.parse(root / 'watchface/manifest.xml').getroot().find('{http://www.garmin.com/xml/connectiq}application')
    version = app.attrib['version']
    if not all(part.isdigit() for part in version.split('.')) or len(version.split('.')) != 3:
        raise ValueError('invalid native version')
    paths = [root/'watchface/manifest.xml', root/'watchface/monkey.jungle']
    watchface = root/'watchface'
    # The generated release jungle includes every native language resource
    # directory. Bind all of them, including currently unqualified locales.
    inputs = [watchface/'source', watchface/'resources']
    inputs.extend(p for p in watchface.glob('resources-*') if p.is_dir())
    for directory in inputs:
        paths.extend(p for p in directory.rglob('*') if p.is_file())
    digest = hashlib.sha256()
    for path in sorted(paths):
        relative = path.relative_to(root).as_posix()
        if relative == GENERATED:
            continue
        data = path.read_bytes()
        digest.update(relative.encode() + b'\0' + str(len(data)).encode() + b'\0' + data)
    identity = digest.hexdigest()[:8]
    return ('// Generated by tools/generate_native_version.py from native build inputs.\n'
            'import Toybox.Lang;\n(:background) module NativeVersion { const BUILD = "' + version +
            '"; const ID = "' + identity + '"; }\n')

def validate(root=ROOT):
    if (root / GENERATED).read_text() != render(root):
        raise ValueError('native build identity is stale; regenerate NativeVersion.mc')

if __name__ == '__main__':
    (ROOT / GENERATED).write_text(render())
