#!/usr/bin/env python3
"""Generate one-at-a-time offline rocket resources from the canonical catalog."""
from pathlib import Path
import json
import re
import subprocess
import struct
import zlib

try:
    from tools.spacefox.catalog import build_catalog
    from tools.spacefox.graphics import export_svg, fit_model_visual
    from tools.spacefox.native_profile import rasterize
except ModuleNotFoundError:
    from spacefox.catalog import build_catalog
    from spacefox.graphics import export_svg, fit_model_visual
    from spacefox.native_profile import rasterize

ROOT = Path(__file__).resolve().parents[1]


def crop_rgba(width, height, pixels):
    """Losslessly crop only all-zero RGBA margins and return PNG and anchor."""
    if len(pixels) != width * height * 4:
        raise ValueError('unexpected model pixel buffer')
    points = [(i % width, i // width) for i in range(width * height)
              if pixels[i*4:i*4+4] != b'\0\0\0\0']
    box = ((min(x for x, y in points), min(y for x, y in points),
            max(x for x, y in points)+1, max(y for x, y in points)+1)
           if points else (0, 0, 1, 1))
    x0, y0, x1, y1 = box
    cropped_width, cropped_height = x1-x0, y1-y0
    rows = [pixels[(y*width+x0)*4:(y*width+x1)*4] for y in range(y0, y1)]
    def chunk(kind, body):
        return (struct.pack('>I', len(body)) + kind + body +
                struct.pack('>I', zlib.crc32(kind + body) & 0xffffffff))
    raw = b''.join(b'\0' + row for row in rows)
    png = (b'\x89PNG\r\n\x1a\n' +
           chunk(b'IHDR', struct.pack('>IIBBBBB', cropped_width, cropped_height, 8, 6, 0, 0, 0)) +
           chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))
    return png, (x0, y0)


def generate(root=ROOT):
    root = Path(root)
    if subprocess.check_output(['rsvg-convert', '--version'], text=True).strip() != 'rsvg-convert version 2.57.0':
        raise ValueError('bundled models require the pinned rsvg-convert 2.57.0')
    catalog = build_catalog(root)
    configurations = catalog['dictionaries']['configurations']
    assets = catalog['dictionaries']['assets']
    bindings = {identity: row['references']['visual'] for identity, row in configurations.items()
                if row['references']['visual'] is not None}
    asset_ids = sorted(set(bindings.values()))
    names = {}
    directory = root / 'watchface/resources/drawables'
    directory.mkdir(parents=True, exist_ok=True)
    rendered = {}
    anchors = {}
    pixels_to_name = {}
    for asset_id in asset_ids:
        asset = assets[asset_id]
        facts = asset['facts']
        if asset['seedCollection'] != 'models' or facts.get('license') != 'MIT':
            raise ValueError('invalid rocket asset ' + asset_id)
        source = root / asset['content']['path']
        visual = fit_model_visual(export_svg(source.read_bytes(), facts['exportSize']))
        pixels, png, _ = rasterize([visual], 54, 124)
        key = bytes(pixels)
        if key not in pixels_to_name:
            name = 'BundledModel%03d' % len(rendered)
            pixels_to_name[key] = name
            rendered[name], anchors[name] = crop_rgba(54, 124, pixels)
        names[asset_id] = pixels_to_name[key]
    groups = [sorted(bindings.items())[i:i + 24] for i in range(0, len(bindings), 24)]
    lines = ['// Generated by tools/build_bundled_models.py from the canonical source catalog.',
             'import Toybox.Lang;', 'module NativeModels {']
    for index, rows in enumerate(groups):
        lines.append(' (:extendedCode) function group%d(id as String) as ResourceId or Null {' % index)
        for identity, asset_id in rows:
            if not re.fullmatch(r'[A-Za-z0-9:_-]+', identity):
                raise ValueError('invalid model identity ' + identity)
            lines.append('  if(id.equals("%s")){return Rez.Drawables.%s;}' % (identity, names[asset_id]))
        lines.append('  return null;}')
    lines.append(' (:extendedCode) function resolve(id as String) as ResourceId or Null {')
    lines.append('  var result=null;')
    for index in range(len(groups)):
        lines.append('  result=group%d(id);if(result!=null){return result;}' % index)
    generic_names = sorted({names[asset_id] for asset_id in asset_ids
                            if assets[asset_id]['facts'].get('kind') == 'generic'})
    lines.extend(['  return null;}',
                  ' (:extendedCode) function hasSpecific(id as String) as Boolean {',
                  '  var found=resolve(id);if(found==null){return false;}'])
    for name in generic_names:
        lines.append('  if(found==Rez.Drawables.%s){return false;}' % name)
    lines.extend(['  return true;}',
                  ' (:extendedCode) function anchor(id as ResourceId) as Array<Number> {'])
    by_anchor = {}
    for name, point in anchors.items():
        by_anchor.setdefault(point, []).append(name)
    for point, group in sorted(by_anchor.items()):
        lines.append('  if(' + '||'.join('id==Rez.Drawables.' + n for n in group) +
                     '){return [%d,%d];}' % point)
    lines.extend(['  return [0,0];}',
                  ' (:extendedCode) function resource(id as String) as ResourceId {',
                  '  var found=resolve(id);if(found!=null){return found as ResourceId;}',
                  '  return Rez.Drawables.Art_unknown;}', '}'])
    resource_xml = '<drawables>\n' + ''.join('<bitmap id="%s" filename="%s.png"/>\n' % (name, name)
                                             for name in sorted(rendered)) + '</drawables>\n'
    for name, png in rendered.items():
        (directory / (name + '.png')).write_bytes(png)
    for path in directory.glob('BundledModel*.png'):
        if re.fullmatch(r'BundledModel\d+\.png', path.name) and path.stem not in rendered:
            path.unlink()
    (directory / 'bundled-models.xml').write_text(resource_xml)
    (root / 'watchface/source/generated/NativeModels.mc').write_text('\n'.join(lines) + '\n')
    return {'configurations': len(bindings), 'unique_assets': len(asset_ids),
            'unique_decoded_pixel_images': len(rendered)}


if __name__ == '__main__':
    print(json.dumps(generate(), sort_keys=True))
